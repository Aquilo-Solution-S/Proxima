#!/usr/bin/env bash
# Dump the schema that replaying the embedded migrations from an empty
# database produces — one file per source, so the composition boundary
# stays visible (docs/contributing.md#migrations):
#
#   schema.core.sql  what core alone provides (proxiima_core, extensions)
#   schema.example.sql  what the example spiice adds (proxiima_example only; its
#                       emitted foreign keys into proxiima_core are the
#                       dependency direction, stated rather than implied)
#
# The ledger bookkeeping tables (public._sqlx_migrations*) are excluded from
# both: they record the replay, they are not what it produces.
#
# On-demand inspection only. Do not commit the output.
# The disposable schema store uses the script-owned store number 0.
#
# Usage:
#   scripts/regen-schema-sql.sh <output-dir>
#
# Environment:
#   PROXIIMA_SCHEMA_PG_URL  admin URL used to create/drop the scratch database
#                          (falls back to PROXIIMA_TEST_PG_URL, then the local
#                          dev default postgres://proxiima:proxiima@localhost:5432/proxiima)
#   PROXIIMA_PG_DUMP        pg_dump command; its major version must be >= the
#                          server's. May be a compound command such as
#                          "docker exec -i <container> pg_dump" — in that case
#                          the URL must resolve identically inside the
#                          container.
set -euo pipefail
cd "$(dirname "$0")/.."

if [ "${1:-}" = "" ] || [ "${1:-}" = "-h" ] || [ "${1:-}" = "--help" ]; then
  echo "usage: scripts/regen-schema-sql.sh <output-dir>" >&2
  exit 2
fi

ADMIN_URL="${PROXIIMA_SCHEMA_PG_URL:-${PROXIIMA_TEST_PG_URL:-postgres://proxiima:proxiima@localhost:5432/proxiima}}"
PG_DUMP="${PROXIIMA_PG_DUMP:-pg_dump}"
OUT_DIR="$1"

SCRATCH="proxiima_schema_replay_$$"
SCRATCH_URL="${ADMIN_URL%/*}/${SCRATCH}"

psql "$ADMIN_URL" -v ON_ERROR_STOP=1 -q -c "CREATE DATABASE \"$SCRATCH\";"
trap 'psql "$ADMIN_URL" -q -c "DROP DATABASE IF EXISTS \"$SCRATCH\" WITH (FORCE);" >/dev/null' EXIT

PROXIIMA_STORE_NUMBER=0 cargo run -q -p proxiima-dev-migrate -- --database-url "$SCRATCH_URL"

# Normalization: version banners, psql \restrict guards, and session SET
# preamble vary across pg_dump minor versions without describing schema.
normalize() {
  grep -vE '^(-- Dumped (from|by) |\\(un)?restrict |SET |SELECT pg_catalog\.set_config)'
}

mkdir -p "$OUT_DIR"
{
  echo "-- Generated by scripts/regen-schema-sql.sh — do not commit."
  echo "-- What core's migrations alone provide."
  $PG_DUMP --schema-only --no-owner --no-privileges \
    --exclude-schema=proxiima_example \
    --exclude-table 'public._sqlx_migrations*' \
    "$SCRATCH_URL" | normalize
} > "$OUT_DIR/schema.core.sql"

{
  echo "-- Generated by scripts/regen-schema-sql.sh — do not commit."
  echo "-- What the example spiice's migrations add on top of core: the"
  echo "-- proxiima_example schema only. Foreign keys into proxiima_core are the"
  echo "-- spiice's dependency on core, stated explicitly."
  $PG_DUMP --schema-only --no-owner --no-privileges \
    --schema=proxiima_example \
    "$SCRATCH_URL" | normalize
} > "$OUT_DIR/schema.example.sql"

echo "wrote $OUT_DIR/schema.core.sql and $OUT_DIR/schema.example.sql"
